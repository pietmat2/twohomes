/**
 * The source catalogue. Every other language is typed against these keys, so a
 * missing or stale translation is a compile error rather than a blank screen.
 *
 * A value is either a plain string or a set of plural forms, chosen with
 * Intl.PluralRules. English and Danish use one/other; Polish needs one/few/many.
 *
 * Placeholders are {braced}. Where a name goes into a slot that an inflected
 * language would have to decline, keep it in a parenthesis or after a colon —
 * see the Polish catalogue for why.
 */
export type Plural = {
  zero?: string
  one: string
  two?: string
  few?: string
  many?: string
  other: string
}

