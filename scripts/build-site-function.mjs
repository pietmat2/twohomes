/*
 * Packs site/ into a single Supabase Edge Function that serves it.
 *
 *   node scripts/build-site-function.mjs            → supabase/functions/site/index.ts
 *
 * Text files are embedded as strings, fonts as base64. One function, no
 * bucket, no build step on the server: the whole site is in the bundle, so a
 * deploy is atomic — the live page is never half-updated.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, relative, posix } from 'node:path';

const SITE = 'site';
const OUT = 'supabase/functions/site/index.ts';

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.woff2': 'font/woff2',
};

/* Everything in site/ except the notes that are for us, not for visitors. */
const SKIP = new Set(['README.md', 'stats.example.json']);

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });

const assets = {};
for (const file of walk(SITE)) {
  const path = posix.join(...relative(SITE, file).split(/[\\/]/));
  if (SKIP.has(path)) continue;

  const ext = path.slice(path.lastIndexOf('.'));
  const type = TYPES[ext];
  if (!type) {
    console.warn(`skipping ${path}: no content type for ${ext}`);
    continue;
  }

  const binary = ext === '.woff2';
  assets[path] = {
    type,
    binary,
    body: binary
      ? readFileSync(file).toString('base64')
      : readFileSync(file, 'utf8'),
    // Fonts and the icon are immutable in practice; the page and its code are
    // not, and stats.json has to be re-read for the counters to move.
    cache:
      path === 'stats.json'
        ? 'public, max-age=30'
        : binary
          ? 'public, max-age=31536000, immutable'
          : 'public, max-age=300',
  };
}

const source = `// Generated by scripts/build-site-function.mjs — do not edit by hand.
// Regenerate with: node scripts/build-site-function.mjs

type Asset = { type: string; body: string; binary: boolean; cache: string };

const ASSETS: Record<string, Asset> = ${JSON.stringify(assets, null, 2)};

const bytes = (b64: string) => Uint8Array.from(atob(b64), (c) => c.charCodeAt(0));

Deno.serve((req: Request) => {
  const url = new URL(req.url);

  // The function answers at /functions/v1/site and at /site. Without the
  // trailing slash the page's own relative links would resolve one level too
  // high, so send the browser to the slashed form first.
  const base = url.pathname.match(/^(\\/functions\\/v1)?\\/site/)?.[0];
  if (base && url.pathname === base) {
    // A path-relative Location, because inside the gateway the request's own
    // origin is http:// and its path has had /functions/v1 stripped — building
    // an absolute URL from it sends the browser somewhere that does not exist.
    return new Response(null, {
      status: 301,
      headers: { location: url.pathname + '/' + url.search },
    });
  }

  let path = base ? url.pathname.slice(base.length) : url.pathname;
  path = path.replace(/^\\//, '');
  if (path === '') path = 'index.html';

  const asset = ASSETS[path];
  if (!asset) {
    return new Response('Not found', {
      status: 404,
      headers: { 'content-type': 'text/plain; charset=utf-8' },
    });
  }

  const headers = new Headers({
    'content-type': asset.type,
    'cache-control': asset.cache,
    'x-content-type-options': 'nosniff',
  });

  if (req.method === 'HEAD') return new Response(null, { headers });

  return new Response(asset.binary ? bytes(asset.body) : asset.body, { headers });
});
`;

mkdirSync('supabase/functions/site', { recursive: true });
writeFileSync(OUT, source);

const total = Object.values(assets).reduce((n, a) => n + a.body.length, 0);
console.log(
  `wrote ${OUT} — ${Object.keys(assets).length} assets, ${Math.round(total / 1024)} kB embedded`
);
for (const [p, a] of Object.entries(assets)) console.log(`  ${p}  ${a.type}`);
